export function useLabels(): Labels {
  const { theme } = useTheme();
  return theme === 'tactical' ? tactical : classic;
}

export const STATUS_ORDER: TaskStatus[] = ['todo', 'in_progress', 'blocked', 'review', 'done'];

export function statusLabel(s: TaskStatus, tactical: boolean): string {
  if (tactical) return ({ todo: 'Ready', in_progress: 'Active', blocked: 'Blocked', review: 'Review', done: 'Accomplished', cancelled: 'Aborted' } as const)[s];
  return ({ todo: 'To do', in_progress: 'In progress', blocked: 'Blocked', review: 'Review', done: 'Done', cancelled: 'Cancelled' } as const)[s];
}
export const PRIORITIES: Priority[] = ['urgent', 'high', 'medium', 'low', 'none'];
export function priorityLabel(p: Priority): string {
  return ({ urgent: 'Urgent', high: 'High', medium: 'Medium', low: 'Low', none: 'No priority' } as const)[p];
}
